-- =========================================================
-- 個人データ基盤（サプリ管理DB）: Snowflakeの準備
-- ステップ0-2〜0-4。上から順に1回だけ実行する
-- （IF NOT EXISTS 付きなので、もう一度流しても壊れない）
-- =========================================================


-- ---------------------------------------------------------
-- 0-2 ウェアハウス（取込・加工・閲覧で分ける）
-- ---------------------------------------------------------
USE ROLE SYSADMIN;

CREATE WAREHOUSE IF NOT EXISTS LOADING_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  COMMENT = '取込用（Fivetran）';

CREATE WAREHOUSE IF NOT EXISTS TRANSFORMING_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  COMMENT = '加工用（dbt）';

CREATE WAREHOUSE IF NOT EXISTS REPORTING_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  COMMENT = '閲覧用（Streamlit）';

-- 使いすぎ防止（リソースモニターはACCOUNTADMINだけが作れる）
USE ROLE ACCOUNTADMIN;

CREATE RESOURCE MONITOR IF NOT EXISTS PERSONAL_DP_MONITOR
  WITH CREDIT_QUOTA = 20
  FREQUENCY = MONTHLY
  START_TIMESTAMP = IMMEDIATELY
  TRIGGERS
    ON 80 PERCENT DO NOTIFY
    ON 100 PERCENT DO SUSPEND;

ALTER WAREHOUSE LOADING_WH      SET RESOURCE_MONITOR = PERSONAL_DP_MONITOR;
ALTER WAREHOUSE TRANSFORMING_WH SET RESOURCE_MONITOR = PERSONAL_DP_MONITOR;
ALTER WAREHOUSE REPORTING_WH    SET RESOURCE_MONITOR = PERSONAL_DP_MONITOR;


-- ---------------------------------------------------------
-- 0-3 データベース（生データと加工済みを分ける）
--   スキーマはここでは作らない。
--   RAWの中はFivetranが、ANALYTICSの中はdbtが初回実行時に作る
-- ---------------------------------------------------------
USE ROLE SYSADMIN;

CREATE DATABASE IF NOT EXISTS RAW
  COMMENT = 'Fivetranが入れた生データ。手で書き換えない';

CREATE DATABASE IF NOT EXISTS ANALYTICS
  COMMENT = 'dbtが作る表';


-- ---------------------------------------------------------
-- 0-4 ロールと権限
-- ---------------------------------------------------------
USE ROLE SECURITYADMIN;

-- ロールを作り、SYSADMINの下につなぐ
CREATE ROLE IF NOT EXISTS LOADER;
CREATE ROLE IF NOT EXISTS TRANSFORMER;
CREATE ROLE IF NOT EXISTS REPORTER;

GRANT ROLE LOADER      TO ROLE SYSADMIN;
GRANT ROLE TRANSFORMER TO ROLE SYSADMIN;
GRANT ROLE REPORTER    TO ROLE SYSADMIN;

-- 自分にも付けて、切り替えて試せるようにする
GRANT ROLE LOADER      TO USER knock190;
GRANT ROLE TRANSFORMER TO USER knock190;
GRANT ROLE REPORTER    TO USER knock190;

-- LOADER：RAWに書く（Fivetran用）
GRANT USAGE ON WAREHOUSE LOADING_WH TO ROLE LOADER;
GRANT USAGE, CREATE SCHEMA, MONITOR ON DATABASE RAW TO ROLE LOADER;

-- TRANSFORMER：RAWを読み、ANALYTICSに書く（dbt用）
GRANT USAGE ON WAREHOUSE TRANSFORMING_WH TO ROLE TRANSFORMER;
GRANT USAGE ON DATABASE RAW TO ROLE TRANSFORMER;
GRANT USAGE  ON FUTURE SCHEMAS IN DATABASE RAW TO ROLE TRANSFORMER;
GRANT SELECT ON FUTURE TABLES  IN DATABASE RAW TO ROLE TRANSFORMER;
GRANT SELECT ON FUTURE VIEWS   IN DATABASE RAW TO ROLE TRANSFORMER;
GRANT USAGE, CREATE SCHEMA ON DATABASE ANALYTICS TO ROLE TRANSFORMER;

-- REPORTER：ANALYTICSを読むだけ（Streamlit用）
--   MARTSだけに絞る調整は、dbtがスキーマを作った後（ステップ2）で行う
GRANT USAGE ON WAREHOUSE REPORTING_WH TO ROLE REPORTER;
GRANT USAGE ON DATABASE ANALYTICS TO ROLE REPORTER;
GRANT USAGE  ON FUTURE SCHEMAS IN DATABASE ANALYTICS TO ROLE REPORTER;
GRANT SELECT ON FUTURE TABLES  IN DATABASE ANALYTICS TO ROLE REPORTER;
GRANT SELECT ON FUTURE VIEWS   IN DATABASE ANALYTICS TO ROLE REPORTER;
